// newVerifyDoc returns the typed documentation for `extend verify` and
// its runs subgroup.
func newVerifyDoc(app *App) *CommandDoc {
	var (
		engine              string
		engineVersion       string
		advancedOptionsPath string
		password            string
		failOn              string
		wait                bool
		timeout             time.Duration
		meta                metaFlags
	)
	return &CommandDoc{
		Use:     "verify <input>",
		Summary: "Check a document for tampering, forgery or AI generation",
		Group:   "Actions",
		Triggers: []string{
			"check a document for tampering or forgery",
			"detect whether a pdf was edited or faked",
			"verify that a bank statement or invoice is authentic",
			"run a fraud check on a document",
			"detect ai-generated or manipulated document images",
		},
		WhenToUse: `Use to check whether a document was tampered with: edited after it was
issued, forged, or generated by AI. It reports a risk level (LOW, MEDIUM
or HIGH), a summary, and the signals behind it with their evidence. To
read values out of a document, use 'extend extract'; for its text,
'extend parse'.`,
		Details: `The input is a local file (uploaded first), a file_xxx ID or an https://
URL to a PDF, JPEG or PNG. Verify checks the file's exact bytes, so there
is no --text input. A PDF gets every check: file structure, signatures,
revision history, layers, fonts, text, and the images on its pages. An
image gets the provenance and image-manipulation checks.

The command starts a run and waits for it: usually under a minute, up to
about 10 minutes with the default engine. --wait=false returns the run at
once; Verify runs send no webhook events, so follow it with 'extend
verify runs watch'.

In a terminal the result reads like this; piped, it's the run's JSON:

    ! HIGH risk: statement.pdf (1 signal)
      Summary: A row was deleted from the fees table after the document was signed.
      Details: extend verify runs get vr_xxx -o json

    LEVEL  SIGNAL                       SUMMARY
    HIGH   DIGITAL_SIGNATURE_INTEGRITY  The document was changed after a no-changes…

The JSON has output.riskLevel (LOW, MEDIUM or HIGH), output.summary and
output.signals: each with a type, riskAssessment.level, a summary, and
evidence that names what was found and where (page and bounding box).

A finished run exits 0 whatever its risk. With --fail-on medium or
--fail-on high it exits 1 when the risk is at or above that level, as it
does when the run fails, so a script goes on only for a document that
passed:

    extend verify statement.pdf --fail-on high && echo "statement.pdf passed"

Options:

  - --engine: verify_agentic (the default) parses the document and runs
    every check, including an agent that reads it for arithmetic,
    sequence, date and identity conflicts. verify_standard is faster for
    screening: it parses only when requireParsing is true and skips the
    agent's checks.
  - --engine-version: an exact release such as 0.1.0, so results stay
    comparable over time, or latest (the default). The run reports the
    resolved version in config.engineVersion.
  - --advanced-options: a JSON object (inline, a path, a file:// URI, or
    '-' for stdin) with one field:
      requireParsing (boolean) - parse the document first, for the checks
      that read its text. verify_agentic always parses and rejects false;
      verify_standard parses only when this is true.

Extend enables Verify per organization (support@extend.ai); until then,
every verify command fails and says so.`,
		Examples: []Example{
			{Label: "Basic", Cmd: "extend verify statement.pdf"},
			{Label: "Fail a script on high risk", Cmd: "extend verify statement.pdf --fail-on high"},
			{Label: "Just the risk level", Cmd: "extend verify invoice.pdf --jq '.output.riskLevel' -o raw"},
			{Label: "Faster screening", Cmd: "extend verify invoice.png --engine verify_standard"},
			{Label: "Async (return the run)", Cmd: "extend verify https://example.com/statement.pdf --wait=false"},
		},
		Gotchas: []string{
			"A finished run exits 0 even when its risk is HIGH; read output.riskLevel or pass --fail-on to act on it.",
			"Verify takes PDF, JPEG and PNG files; any other type fails with FILE_TYPE_NOT_SUPPORTED.",
			"verify_agentic always parses, so --advanced-options '{\"requireParsing\":false}' needs --engine verify_standard.",
			"--fail-on needs the result, so it can't be combined with --wait=false; use 'extend verify runs watch <id> --fail-on high' instead.",
		},
		SeeAlso:  []string{"verify runs watch", "verify runs get", "verify runs list", "extract", "parse"},
		Output:   OutputSpec{TTY: OutputPretty, Pipe: OutputJSON},
		Wait:     &WaitSpec{Profile: extendx.ProfileShort, DefaultsToWait: true},
		Failures: []extendx.RunStatus{extendx.StatusFailed, extendx.StatusCancelled},
		Args: func(cmd *cobra.Command, args []string) error {
			if len(args) != 1 {
				return fmt.Errorf("verify takes one input (a file path, file_xxx ID or https:// URL), got %d", len(args))
			}
			return nil
		},
		RunE: func(cmd *cobra.Command, args []string) error {
			gate, err := parseFailOn(failOn)
			if err != nil {
				return err
			}
			md, err := meta.build()
			if err != nil {
				return err
			}
			return runVerify(cmd.Context(), app, verifyParams{
				input:               args[0],
				engine:              engine,
				engineVersion:       engineVersion,
				advancedOptionsPath: advancedOptionsPath,
				password:            password,
				metadata:            md,
				failOn:              gate,
				wait:                wait,
				timeout:             timeout,
			})
		},
		Configure: func(cmd *cobra.Command) {
			cmd.Flags().StringVar(&engine, "engine", "", "Engine: verify_agentic (the default; parses and runs every check) or verify_standard (faster screening)")
			cmd.Flags().StringVar(&engineVersion, "engine-version", "", "Verify engine release, e.g. 0.1.0, or latest (the default); the run reports the resolved version")
			cmd.Flags().StringVar(&advancedOptionsPath, "advanced-options", "", "Verify options as a JSON object: requireParsing. Source: inline JSON, path, file:// URI, or '-' for stdin")
			cmd.Flags().StringVar(&password, "password", "", "Password for a password-protected PDF (URL inputs only)")
			cmd.Flags().StringVar(&failOn, "fail-on", "", "Exit 1 when the run's risk is at or above this level: medium or high")
			cmd.Flags().BoolVar(&wait, "wait", true, "Wait for the run to reach a terminal state (--wait=false returns the run immediately)")
			cmd.Flags().DurationVar(&timeout, "timeout", 30*time.Minute, "Maximum total time to wait for the run to reach a terminal state (not a per-HTTP-request timeout; see --http-timeout)")
			meta.attach(cmd)
		},
		Subcommands: []*CommandDoc{verifyRunsSpec().doc(app)},
	}
}

type verifyParams struct {
	input               string
	engine              string
	engineVersion       string
	advancedOptionsPath string
	password            string
	metadata            map[string]any
	failOn              extend.VerifyRiskLevel
	wait                bool
	timeout             time.Duration
}

func runVerify(ctx context.Context, app *App, p verifyParams) error {
	if p.failOn != "" && !p.wait {
		return fmt.Errorf("--fail-on needs the run's result, so it can't be used with --wait=false; follow the run with 'extend verify runs watch <id> --fail-on %s'", strings.ToLower(string(p.failOn)))
	}
	cfg, err := verifyConfig(p)
	if err != nil {
		return err
	}
	cli, err := app.NewClient()
	if err != nil {
		return err
	}
	ref, err := uploadOrResolveWith(ctx, app, cli, p.input, p.password)
	if err != nil {
		return err
	}
	file, err := extendx.BuildVerifyFile(ref)
	if err != nil {
		return err
	}
	req := &extend.VerifyRunsCreateRequest{File: file, Config: cfg}
	if p.metadata != nil {
		md := extend.RunMetadata(p.metadata)
		req.Metadata = &md
	}

	run, err := extendx.StartOnce(ctx, func(opts ...option.RequestOption) (*extend.VerifyRun, error) {
		return cli.VerifyRuns.Create(ctx, req, opts...)
	})
	if err != nil {
		return verifyNotEnabled(fmt.Errorf("create run: %w", err))
	}
	if !p.wait {
		return renderWithDefault(app, run, output.FormatJSON)
	}

	sp := app.IO.StartSpinner(fmt.Sprintf("Run %s: %s", run.ID, run.Status))
	final, err := waitForVerifyRun(ctx, cli, run.ID, extendx.WaitProfileOptions(extendx.ProfileShort, p.timeout), func(r *extend.VerifyRun) {
		sp.Update(fmt.Sprintf("Run %s: %s", r.ID, r.Status))
	})
	sp.Stop("")
	if err != nil {
		return formatActionWaitError(verifyNotEnabled(err), run.ID, "extend verify runs watch")
	}
	if err := renderVerifyResult(app, final); err != nil {
		return err
	}
	switch extendx.RunStatus(final.Status) {
	case extendx.StatusFailed:
		return runFailureError(final.ID, final.FailureReason, final.FailureMessage)
	case extendx.StatusCancelled:
		return fmt.Errorf("run %s was cancelled", final.ID)
	}
	return riskGate(final, p.failOn)
}

// verifyConfig builds the run config from the flags, or nil when none is
// set so the API applies its defaults.
func verifyConfig(p verifyParams) (*extend.VerifyConfig, error) {
	if p.engine == "" && p.engineVersion == "" && p.advancedOptionsPath == "" {
		return nil, nil
	}
	cfg := &extend.VerifyConfig{}
	if p.engine != "" {
		e := extend.VerifyEngine(p.engine)
		cfg.Engine = &e
	}
	if p.engineVersion != "" {
		cfg.EngineVersion = extend.String(p.engineVersion)
	}
	if p.advancedOptionsPath != "" {
		raw, err := readJSONFile(p.advancedOptionsPath, "--advanced-options")
		if err != nil {
			return nil, err
		}
		var ao extend.VerifyAdvancedOptions
		if err := json.Unmarshal(raw, &ao); err != nil {
			return nil, fmt.Errorf("--advanced-options: %w", err)
		}
		cfg.AdvancedOptions = &ao
	}
	return cfg, nil
}

func waitForVerifyRun(ctx context.Context, c *sdkclient.Client, id string, opts extendx.WaitOptions, onPoll func(*extend.VerifyRun)) (*extend.VerifyRun, error) {
	return extendx.PollForRun(ctx,
		func(ctx context.Context) (*extend.VerifyRun, error) {
			return c.VerifyRuns.Retrieve(ctx, id, &extend.VerifyRunsRetrieveRequest{})
		},
		func(r *extend.VerifyRun) extendx.RunStatus { return extendx.RunStatus(r.Status) },
		opts, onPoll,
	)
}

// verifyNotEnabled explains the bare 404 every Verify endpoint returns
// until Extend enables Verify for the organization, which otherwise reads
// like a missing run or file (those 404s name what's missing).
func verifyNotEnabled(err error) error {
	apiErr, ok := extendx.AsAPIError(err)
	if !ok || apiErr.StatusCode != http.StatusNotFound || strings.TrimSpace(apiErr.Message) != "Not found." {
		return err
	}
	msg := "Verify isn't enabled for this organization; ask Extend to enable it (support@extend.ai)"
	if apiErr.RequestID != "" {
		msg += fmt.Sprintf(" (request %s)", apiErr.RequestID)
	}
	return errors.New(msg)
}

var verifyRiskRank = map[extend.VerifyRiskLevel]int{
	extend.VerifyRiskLevelLow:    1,
	extend.VerifyRiskLevelMedium: 2,
	extend.VerifyRiskLevelHigh:   3,
}

// parseFailOn reads --fail-on. LOW isn't accepted: every result is at or
// above it.
func parseFailOn(s string) (extend.VerifyRiskLevel, error) {
	switch level := extend.VerifyRiskLevel(strings.ToUpper(strings.TrimSpace(s))); level {
	case "", extend.VerifyRiskLevelMedium, extend.VerifyRiskLevelHigh:
		return level, nil
	}
	return "", fmt.Errorf("--fail-on must be medium or high, got %q", s)
}

// riskGate fails a run whose risk is at or above failOn, and one whose
// risk can't be read, so --fail-on never passes a document it couldn't
// check.
func riskGate(run *extend.VerifyRun, failOn extend.VerifyRiskLevel) error {
	if failOn == "" {
		return nil
	}
	if run.Output == nil {
		return fmt.Errorf("run %s has no result to check against --fail-on (status %s)", run.ID, run.Status)
	}
	level := run.Output.RiskLevel
	rank, known := verifyRiskRank[level]
	if !known {
		return fmt.Errorf("run %s has risk level %q, which --fail-on doesn't know", run.ID, level)
	}
	if rank >= verifyRiskRank[failOn] {
		return fmt.Errorf("run %s found %s risk, at or above --fail-on %s", run.ID, level, strings.ToLower(string(failOn)))
	}
	return nil
}

// renderVerifyResult prints the risk, summary and signals in a terminal,
// and the run's JSON otherwise.
func renderVerifyResult(app *App, run *extend.VerifyRun) error {
	if app.Format != "" || app.JQ != "" || !app.IO.IsStdoutTTY() {
		return renderWithDefault(app, run, output.FormatJSON)
	}
	pal := paletteFor(app.IO)
	w := app.IO.Out
	status := extendx.RunStatus(run.Status)
	if status != extendx.StatusProcessed || run.Output == nil {
		fmt.Fprintf(w, "%s %s (%s)\n", statusIcon(pal, status), run.ID, run.Status)
		var reason []string
		for _, s := range []*string{run.FailureReason, run.FailureMessage} {
			if s != nil && *s != "" {
				reason = append(reason, *s)
			}
		}
		if len(reason) > 0 {
			fmt.Fprintf(w, "  %s\n", strings.Join(reason, ": "))
		}
		return nil
	}

	out := run.Output
	head := fmt.Sprintf("%s risk", out.RiskLevel)
	if run.File != nil && run.File.Name != "" {
		head += ": " + run.File.Name
	}
	count := "no signals"
	if n := len(out.Signals); n > 0 {
		count = fmt.Sprintf("%d signal%s", n, pluralize(n))
	}
	icon, color := riskStyle(pal, out.RiskLevel)
	fmt.Fprintf(w, "%s %s (%s)\n", icon, color(head), count)
	if s := strings.TrimSpace(out.Summary); s != "" {
		fmt.Fprintf(w, "  Summary: %s\n", s)
	}
	fmt.Fprintf(w, "  %s\n", pal.Dimf("Details: extend verify runs get %s -o json", run.ID))
	if len(out.Signals) == 0 {
		return nil
	}

	signals := slices.Clone(out.Signals)
	slices.SortStableFunc(signals, func(a, b *extend.VerifySignal) int {
		return verifyRiskRank[signalLevel(b)] - verifyRiskRank[signalLevel(a)]
	})
	rows := make([][]string, len(signals))
	for i, s := range signals {
		rows[i] = []string{string(signalLevel(s)), string(s.Type), truncate(strings.Join(strings.Fields(s.Summary), " "), 80)}
	}
	fmt.Fprintln(w)
	return output.RenderTable(w, []string{"level", "signal", "summary"}, rows)
}

func signalLevel(s *extend.VerifySignal) extend.VerifyRiskLevel {
	if s == nil || s.RiskAssessment == nil {
		return ""
	}
	return s.RiskAssessment.Level
}

// riskStyle colors a result by its risk level, not its run status, so a
// risky document never gets a green check.
func riskStyle(p palette, level extend.VerifyRiskLevel) (string, colorFn) {
	switch level {
	case extend.VerifyRiskLevelLow:
		return p.Green("✓"), p.Green
	case extend.VerifyRiskLevelMedium:
		return p.Yellow("!"), p.Yellow
	case extend.VerifyRiskLevelHigh:
		return p.Red("!"), p.Red
	}
	return "•", func(s string) string { return s }
}
